function stored(key) {
  try { return localStorage.getItem(`workbench.${key}`); } catch { return null; }
}
function store(key, value) {
  try { localStorage.setItem(`workbench.${key}`, value); } catch { /* Preferences stay in-memory without storage. */ }
}
function initialLang() {
  return stored('uiLang') || (navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en');
}
export function initialTheme() {
  const saved = stored('theme');
  if (saved === 'light' || saved === 'dark') return saved;
  return typeof matchMedia === 'function' && matchMedia('(prefers-color-scheme: light)').matches ? 'light' : 'dark';
}

export const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(initialLang);
  const setLang = useCallback((next) => {
    setLangState(next);
    store('uiLang', next);
  }, []);
  useEffect(() => { document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en'; }, [lang]);
  const t = useCallback((key, vars) => {
    let text = dict[lang]?.[key] ?? dict.en[key] ?? key;
    if (vars) for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
    return text;
  }, [lang]);
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useT() {
  return useContext(I18nContext).t;
}
export function useLangControls() {
  const { lang, setLang } = useContext(I18nContext);
  return { lang, setLang };
}
